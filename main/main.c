/* ====================================== */
/* 4. 任务函数实现区                        */
/*    每个任务都是一个无限循环 for(;;)       */
/* ====================================== */
static void led_task(void *arg)
{
    (void) arg;

    /* 4.1 GPIO8 配成输出（enable_w1ts：写 1 使能对应位） */
    GPIO->enable_w1ts.val = (1U << LED_PIN);

    /* 4.2 周期业务：500ms 低 + 500ms 高 */
    for (;;)
    {
        GPIO->out_w1tc.val = (1U << LED_PIN);   /* 输出低 */
        vTaskDelay(pdMS_TO_TICKS(500));         /* 阻塞 500ms，让出 CPU */

        GPIO->out_w1ts.val = (1U << LED_PIN);   /* 输出高 */
        vTaskDelay(pdMS_TO_TICKS(500));
    }
}

